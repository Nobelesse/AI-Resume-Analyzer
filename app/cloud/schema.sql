-- AI Resume Analyzer, isolated cloud schema. This file does not touch SQLite.
-- Run as a trusted Supabase database owner; do not expose database credentials.
BEGIN;
CREATE SCHEMA IF NOT EXISTS ara_cloud;
SET search_path TO ara_cloud, public;

CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT NOT NULL,
  display_name TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('admin','user')),
  is_active INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0,1)),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS ara_users_email_ci ON users(lower(email));
CREATE UNIQUE INDEX IF NOT EXISTS ara_one_admin ON users(role) WHERE role = 'admin';

CREATE OR REPLACE FUNCTION ara_guard_admin() RETURNS trigger LANGUAGE plpgsql SET search_path = ara_cloud, pg_temp AS $$
BEGIN
  IF TG_OP = 'DELETE' AND OLD.role = 'admin' THEN
    RAISE EXCEPTION 'Permanent administrator cannot be deleted';
  END IF;
  IF TG_OP = 'UPDATE' AND OLD.role = 'admin' THEN
    RAISE EXCEPTION 'Permanent administrator cannot be modified';
  END IF;
  IF TG_OP = 'UPDATE' AND OLD.role <> 'admin' AND NEW.role = 'admin' THEN
    RAISE EXCEPTION 'Administrator promotion is disabled';
  END IF;
  RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
END $$;
DROP TRIGGER IF EXISTS ara_guard_admin_trigger ON users;
CREATE TRIGGER ara_guard_admin_trigger BEFORE UPDATE OR DELETE ON users
  FOR EACH ROW EXECUTE FUNCTION ara_guard_admin();

CREATE TABLE IF NOT EXISTS login_throttle (
  identifier TEXT PRIMARY KEY,
  failure_count INTEGER NOT NULL DEFAULT 0,
  blocked_until BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS activity_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  event TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  actor_email_snapshot TEXT,
  actor_original_id BIGINT
);
CREATE INDEX IF NOT EXISTS ara_activity_actor ON activity_logs(actor_id);
CREATE OR REPLACE FUNCTION ara_audit_snapshot() RETURNS trigger LANGUAGE plpgsql SET search_path = ara_cloud, pg_temp AS $$
BEGIN
  IF NEW.actor_id IS NOT NULL THEN
    SELECT email INTO NEW.actor_email_snapshot FROM users WHERE id = NEW.actor_id;
    NEW.actor_original_id := NEW.actor_id;
  END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS ara_audit_snapshot_insert ON activity_logs;
CREATE TRIGGER ara_audit_snapshot_insert BEFORE INSERT ON activity_logs
 FOR EACH ROW EXECUTE FUNCTION ara_audit_snapshot();
CREATE OR REPLACE FUNCTION ara_snapshot_before_user_delete() RETURNS trigger LANGUAGE plpgsql SET search_path = ara_cloud, pg_temp AS $$
BEGIN
  UPDATE activity_logs SET
    actor_email_snapshot = COALESCE(actor_email_snapshot, OLD.email),
    actor_original_id = COALESCE(actor_original_id, OLD.id)
  WHERE actor_id = OLD.id;
  RETURN OLD;
END $$;
DROP TRIGGER IF EXISTS ara_user_delete_audit ON users;
CREATE TRIGGER ara_user_delete_audit BEFORE DELETE ON users
 FOR EACH ROW EXECUTE FUNCTION ara_snapshot_before_user_delete();

CREATE TABLE IF NOT EXISTS resumes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  original_filename TEXT NOT NULL,
  storage_name TEXT NOT NULL UNIQUE,
  file_type TEXT NOT NULL CHECK (file_type IN ('pdf','docx','txt','rtf','odt')),
  file_size BIGINT NOT NULL,
  document_type TEXT NOT NULL DEFAULT 'resume' CHECK (document_type IN ('resume','cv')),
  sha256 TEXT NOT NULL,
  extracted_text TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (file_size > 0 AND ((document_type='resume' AND file_size<=2000000)
    OR (document_type='cv' AND file_size<=10000000)))
);
CREATE INDEX IF NOT EXISTS ara_resumes_owner ON resumes(owner_id,id DESC);
CREATE TABLE IF NOT EXISTS analyses (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  resume_id BIGINT NOT NULL REFERENCES resumes(id) ON DELETE CASCADE,
  owner_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  score INTEGER NOT NULL CHECK (score BETWEEN 0 AND 100),
  result_json TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ara_analyses_owner ON analyses(owner_id,id DESC);
CREATE TABLE IF NOT EXISTS job_matches (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  resume_id BIGINT NOT NULL REFERENCES resumes(id) ON DELETE CASCADE,
  job_title TEXT NOT NULL,
  job_description TEXT NOT NULL,
  result_json TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ara_matches_owner ON job_matches(owner_id,id DESC);

CREATE TABLE IF NOT EXISTS skills (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL, normalized TEXT NOT NULL UNIQUE,
  category TEXT NOT NULL, source TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS ara_skills_category ON skills(category);
CREATE TABLE IF NOT EXISTS skill_aliases (
  alias TEXT PRIMARY KEY,
  skill_id BIGINT NOT NULL REFERENCES skills(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS ara_skill_alias_id ON skill_aliases(skill_id);
CREATE TABLE IF NOT EXISTS tax_occupations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source TEXT NOT NULL, source_id TEXT NOT NULL, name TEXT NOT NULL,
  normalized TEXT NOT NULL,
  UNIQUE(source,source_id)
);
CREATE INDEX IF NOT EXISTS ara_tax_occ_normalized ON tax_occupations(normalized);
CREATE TABLE IF NOT EXISTS tax_skills (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source TEXT NOT NULL, source_id TEXT NOT NULL, name TEXT NOT NULL,
  normalized TEXT NOT NULL,
  UNIQUE(source,source_id)
);
CREATE INDEX IF NOT EXISTS ara_tax_skill_normalized ON tax_skills(normalized);
CREATE TABLE IF NOT EXISTS tax_links (
  occupation_id BIGINT NOT NULL REFERENCES tax_occupations(id) ON DELETE CASCADE,
  skill_id BIGINT NOT NULL REFERENCES tax_skills(id) ON DELETE CASCADE,
  relation TEXT NOT NULL,
  PRIMARY KEY(occupation_id,skill_id,relation)
);
CREATE INDEX IF NOT EXISTS ara_tax_link_skill ON tax_links(skill_id,occupation_id);
CREATE TABLE IF NOT EXISTS tax_occupation_aliases (
  source TEXT NOT NULL, alias TEXT NOT NULL,
  occupation_id BIGINT NOT NULL REFERENCES tax_occupations(id) ON DELETE CASCADE,
  PRIMARY KEY(source,alias,occupation_id)
);
CREATE INDEX IF NOT EXISTS ara_tax_occ_alias ON tax_occupation_aliases(alias);
CREATE TABLE IF NOT EXISTS tax_skill_aliases (
  source TEXT NOT NULL, alias TEXT NOT NULL,
  skill_id BIGINT NOT NULL REFERENCES tax_skills(id) ON DELETE CASCADE,
  PRIMARY KEY(source,alias,skill_id)
);
CREATE INDEX IF NOT EXISTS ara_tax_skill_alias ON tax_skill_aliases(alias);
CREATE TABLE IF NOT EXISTS tax_imports (
  source TEXT PRIMARY KEY, version TEXT NOT NULL,
  imported_at TEXT NOT NULL
);
-- Only a trusted server connection must access ara_cloud. No anon/authenticated
-- role should receive schema grants; ensure REST exposed schemas exclude it.
REVOKE ALL ON SCHEMA ara_cloud FROM PUBLIC;
COMMIT;
